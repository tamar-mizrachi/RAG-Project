import asyncio
import gradio as gr


def build_ui(async_answer):
    async def respond(message, history):
        if not message or not message.strip():
            return "Please enter a question."

        result = await async_answer(message.strip())
        source_text = ""
        if result.sources:
            source_text = "\n\nSources:\n" + "\n".join(
                f"- {s.get('tool','unknown')} | {s.get('file','unknown')}"
                + (f" | {s.get('heading')}" if s.get("heading") else "")
                for s in result.sources
            )

        return (
            f"{result.answer}\n\n"
            f"Route: {result.route} | Confidence: {result.confidence:.2f}"
            f"{source_text}"
        )

    return gr.ChatInterface(
        fn=respond,
        title="Agentic Coding RAG Assistant",
        description=(
            "Ask questions about the Markdown documentation generated by "
            "Cursor, Kiro and Claude Code. The system routes each question "
            "to semantic or structured retrieval."
        ),
        examples=[
            ["How is the application installed?"],
            ["List all technical decisions."],
            ["What is the latest RTL rule?"],
            ["What warnings were recorded?"],
            ["What changed recently?"],
        ],
    )
